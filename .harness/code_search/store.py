def _connect(path: Path) -> sqlite3.Connection:
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA synchronous=NORMAL")
    return conn


def _reset_incompatible_database(path: Path) -> None:
    """Discard incompatible derived state instead of carrying migrations forever."""
    if not path.exists():
        return
    with closing(sqlite3.connect(path)) as conn:
        version = int(conn.execute("PRAGMA user_version").fetchone()[0])
        has_schema = bool(conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='code_files'"
        ).fetchone())
    if has_schema and version != SCHEMA_VERSION:
        for candidate in (path, Path(f"{path}-wal"), Path(f"{path}-shm")):
            try:
                candidate.unlink()
            except FileNotFoundError:
                pass


