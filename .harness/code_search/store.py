_FTS_STOP_TERMS = {
    "a", "an", "and", "are", "as", "at", "be", "been", "before", "by", "can",
    "code", "does", "find", "for", "from", "how", "in", "into", "is", "it", "its",
    "of", "on", "or", "show", "that", "the", "their", "then", "this", "to", "where",
    "which", "with", "would", "could", "should", "when", "what", "who", "why",
}


def identifier_lexemes(value: str) -> list[str]:
    """Return deterministic language-neutral lexical forms for code identifiers.

    The structural parsers intentionally preserve each language's native symbol
    spelling. Lexical retrieval still needs common source conventions to compare
    naturally: ``bearer-token``, ``bearer_token``, ``BearerToken``,
    ``getHTTPResponse``, Java/Swift dotted members, Go receiver notation, Smali
    arrows, paths, and similar spellings should contribute compatible terms.

    This helper is deliberately syntax-agnostic. It does not stem or guess a
    programming language; it only decomposes punctuation and ASCII case
    boundaries while preserving compact forms. Adjacent recombinations retain
    useful forms such as ``OAuth2`` and ``URLSession`` that naive camel-case
    splitting can otherwise damage.
    """
    text = str(value or "").strip()
    if not text:
        return []

    coarse: list[str] = []
    current: list[str] = []
    for char in text:
        if char.isalnum():
            current.append(char)
        elif current:
            coarse.append("".join(current))
            current = []
    if current:
        coarse.append("".join(current))

    output: list[str] = []
    seen: set[str] = set()

    def add(term: str) -> None:
        normalized = term.casefold().strip()
        if len(normalized) < 2 or normalized in seen:
            return
        seen.add(normalized)
        output.append(normalized)

    for segment in coarse:
        add(segment)
        # Standard language-neutral boundaries: lower/digit -> upper and
        # acronym -> TitleCase (HTTPResponse -> HTTP + Response).
        split = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", segment)
        split = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", split)
        parts = [part for part in split.split() if part]
        for part in parts:
            add(part)
        # Recombine adjacent pieces as aliases. This recovers mixed-brand and
        # acronym forms such as O + Auth2 -> oauth2 and URL + Session ->
        # urlsession without language- or framework-specific dictionaries.
        for width in (2, 3):
            for index in range(0, max(0, len(parts) - width + 1)):
                add("".join(parts[index:index + width]))

    return output


def _raw_fts_terms(query: str) -> list[str]:
    # Keep common source punctuation in the original token so exact spellings
    # remain useful; identifier_lexemes() contributes separator/case aliases.
    # str.isalnum() deliberately preserves non-ASCII identifier text supported
    # by SQLite unicode61 instead of restricting lexical retrieval to English.
    allowed_punctuation = {"_", "$", "@", "#", ".", "/", ":", "-"}
    terms: list[str] = []
    current: list[str] = []
    for char in str(query or ""):
        if char.isalnum() or char in allowed_punctuation:
            current.append(char)
            continue
        if len(current) >= 2:
            terms.append("".join(current))
        current = []
    if len(current) >= 2:
        terms.append("".join(current))
    return terms


def _fts_query_terms(query: str, *, limit: int = 24) -> list[str]:
    raw_terms = _raw_fts_terms(query)
    terms: list[str] = []
    seen: set[str] = set()

    def add(term: str) -> None:
        normalized = str(term or "").casefold().strip()
        if len(normalized) < 2 or normalized in _FTS_STOP_TERMS or normalized in seen:
            return
        seen.add(normalized)
        terms.append(str(term))

    for raw in raw_terms:
        add(raw)
        for alias in identifier_lexemes(raw):
            add(alias)
        if len(terms) >= limit:
            break

    # Preserve the historical all-stop-word behavior instead of turning a
    # lexical request into an empty query.
    if not terms:
        for raw in raw_terms:
            normalized = raw.casefold()
            if normalized not in seen:
                seen.add(normalized)
                terms.append(raw)
            if len(terms) >= limit:
                break
    return terms[:limit]


def _fts_query(query: str) -> str:
    terms = _fts_query_terms(query)
    return " OR ".join(f'"{term.replace(chr(34), chr(34) * 2)}"' for term in terms)


def _identifier_bridge_terms(query: str, *, limit: int = 12) -> list[str]:
    """Specific atoms used to bridge tokenizer/case conventions.

    These are substring predicates over bounded structural metadata and text,
    not semantic expansion or stemming. Long/specific terms are considered
    first so generic role words cannot dominate the bridge.
    """
    ordered: list[str] = []
    seen: set[str] = set()
    for raw in _raw_fts_terms(query):
        candidates = identifier_lexemes(raw) or [raw.casefold()]
        for term in candidates:
            normalized = term.casefold()
            if len(normalized) < 3 or normalized in _FTS_STOP_TERMS or normalized in seen:
                continue
            seen.add(normalized)
            ordered.append(normalized)
    ordered.sort(key=lambda value: (-len(value), value))
    return ordered[:limit]


def _identifier_bridge_rows(
    conn: sqlite3.Connection,
    project_id: str,
    branch_key: str,
    query: str,
    limit: int,
) -> list[dict[str, Any]]:
    """Bounded lexical bridge for separator/case-tokenizer mismatches.

    FTS5 cannot match a suffix inside one camelCase token (``bearer`` inside
    ``validateBearerToken``), and Awoki intentionally keeps punctuation such as
    ``-`` tokenized for paths/API names. This secondary local lexical pass only
    compares literal query atoms against already-indexed path/symbol/signature
    metadata and chunk text. It is language-neutral and network-free.
    """
    terms = _identifier_bridge_terms(query)
    if not terms:
        return []

    coverage_parts: list[str] = []
    weighted_parts: list[str] = []
    where_parts: list[str] = []
    coverage_params: list[Any] = []
    weighted_params: list[Any] = []
    where_params: list[Any] = []

    for term in terms:
        # Each atom counts once for coverage when it occurs in any indexed
        # representation. Structural identity fields carry higher weight than
        # source text, which keeps ordinary prose/code-body coincidences weak.
        predicate = (
            "instr(lower(f.path), ?) > 0 OR "
            "instr(lower(c.symbol_name), ?) > 0 OR "
            "instr(lower(c.qualified_name), ?) > 0 OR "
            "instr(lower(COALESCE(s.signature,'')), ?) > 0 OR "
            "instr(lower(c.text), ?) > 0"
        )
        coverage_parts.append(f"CASE WHEN ({predicate}) THEN 1 ELSE 0 END")
        coverage_params.extend([term] * 5)

        weighted_parts.append(
            "(CASE WHEN instr(lower(c.symbol_name), ?) > 0 THEN 8 ELSE 0 END + "
            " CASE WHEN instr(lower(c.qualified_name), ?) > 0 THEN 6 ELSE 0 END + "
            " CASE WHEN instr(lower(f.path), ?) > 0 THEN 5 ELSE 0 END + "
            " CASE WHEN instr(lower(COALESCE(s.signature,'')), ?) > 0 THEN 3 ELSE 0 END + "
            " CASE WHEN instr(lower(c.text), ?) > 0 THEN 1 ELSE 0 END)"
        )
        weighted_params.extend([term] * 5)
        where_parts.append(f"({predicate})")
        where_params.extend([term] * 5)

    coverage_sql = " + ".join(coverage_parts) or "0"
    weighted_sql = " + ".join(weighted_parts) or "0"
    where_sql = " OR ".join(where_parts) or "0"
    params = coverage_params + weighted_params + where_params + [
        project_id, branch_key, max(1, min(int(limit), 200))
    ]

    sql = f"""
        SELECT c.*, f.project_id, f.repo_id, f.source_id, f.source_type, f.revision_key,
               f.revision_label, f.content_identity, f.branch_key, f.branch_name,
               f.commit_sha, f.dirty, f.path, f.language, f.parser_id,
               f.parse_mode, f.parse_status, f.diagnostics_json, s.signature,
               ({coverage_sql}) AS lexical_coverage,
               ({weighted_sql}) AS lexical_weight
        FROM code_chunks c
        JOIN code_files f ON f.file_id=c.file_id
        LEFT JOIN code_symbols s ON s.symbol_id=c.symbol_id
        WHERE ({where_sql}) AND f.project_id=? AND f.branch_key=?
        ORDER BY lexical_coverage DESC, lexical_weight DESC, f.path, c.start_line, c.chunk_id
        LIMIT ?
    """
    rows = conn.execute(sql, params).fetchall()
    out: list[dict[str, Any]] = []
    for row in rows:
        item = dict(row)
        haystacks = [
            str(item.get("path") or "").casefold(),
            str(item.get("symbol_name") or "").casefold(),
            str(item.get("qualified_name") or "").casefold(),
            str(item.get("signature") or "").casefold(),
            str(item.get("text") or "").casefold(),
        ]
        item["lexical_normalization_terms"] = [
            term for term in terms if any(term in value for value in haystacks)
        ]
        item["lexical_match_mode"] = "identifier_bridge"
        out.append(item)
    return out


def search_fts(path: Path, project_id: str, branch_key: str, query: str, limit: int) -> list[dict[str, Any]]:
    init_db(path)
    expression = _fts_query(query)
    if not expression:
        return []
    bounded_limit = max(1, min(int(limit), 200))
    with closing(_connect(path)) as conn:
        try:
            direct_rows = conn.execute(
                """
                SELECT fts.chunk_id, bm25(code_chunks_fts, 0.0, 0.0, 0.0, 0.0, 1.8, 1.2, 2.5, 3.0, 2.0, 1.0) AS rank,
                       c.*, f.project_id, f.repo_id, f.source_id, f.source_type, f.revision_key, f.revision_label, f.content_identity, f.branch_key, f.branch_name,
                       f.commit_sha, f.dirty, f.path, f.language, f.parser_id,
                       f.parse_mode, f.parse_status, f.diagnostics_json, s.signature
                FROM code_chunks_fts fts
                JOIN code_chunks c ON c.chunk_id=fts.chunk_id
                JOIN code_files f ON f.file_id=c.file_id
                LEFT JOIN code_symbols s ON s.symbol_id=c.symbol_id
                WHERE code_chunks_fts MATCH ? AND f.project_id=? AND f.branch_key=?
                ORDER BY rank LIMIT ?
                """,
                (expression, project_id, branch_key, bounded_limit),
            ).fetchall()
        except sqlite3.OperationalError:
            direct_rows = []
        try:
            bridge_rows = _identifier_bridge_rows(conn, project_id, branch_key, query, bounded_limit)
        except sqlite3.OperationalError:
            # The bridge is supplemental. A malformed/unsupported local SQLite
            # expression must never erase otherwise-valid native FTS results.
            bridge_rows = []

        # Fuse the native FTS5 order and identifier-normalization bridge locally.
        # This preserves BM25 as the primary lexical signal while giving strong
        # separator/camel-case matches a bounded independent lexical opportunity.
        merged: dict[str, dict[str, Any]] = {}
        k = 40.0
        for rank, row in enumerate(direct_rows, start=1):
            item = dict(row)
            item["fts_raw_score"] = 1.0 / (1.0 + abs(float(item.pop("rank") or 0.0)))
            item["lexical_match_mode"] = "sqlite_fts"
            item["lexical_normalization_terms"] = []
            item["_lexical_rrf"] = 1.0 / (k + rank)
            merged[str(item["chunk_id"])] = item

        for rank, row in enumerate(bridge_rows, start=1):
            item = dict(row)
            key = str(item["chunk_id"])
            contribution = 0.75 / (k + rank)
            existing = merged.get(key)
            if existing is None:
                item["fts_raw_score"] = 0.0
                item["_lexical_rrf"] = contribution
                merged[key] = item
            else:
                existing["_lexical_rrf"] = float(existing.get("_lexical_rrf") or 0.0) + contribution
                existing["lexical_match_mode"] = "sqlite_fts+identifier_bridge"
                existing["lexical_normalization_terms"] = list(item.get("lexical_normalization_terms") or [])
                existing["lexical_coverage"] = item.get("lexical_coverage")
                existing["lexical_weight"] = item.get("lexical_weight")

        ranked = sorted(
            merged.values(),
            key=lambda item: (
                -float(item.get("_lexical_rrf") or 0.0),
                str(item.get("path") or ""),
                int(item.get("start_line") or 0),
                str(item.get("chunk_id") or ""),
            ),
        )[:bounded_limit]
        out: list[dict[str, Any]] = []
        for item in ranked:
            item = dict(item)
            item["score"] = float(item.pop("_lexical_rrf") or 0.0)
            item["retrieval_backend"] = "code_fts"
            out.append(item)
        return out


def _literal_like_pattern(value: str) -> str:
    # LIKE is useful for bounded source/path substring lookup, but `%` and `_`
    # must remain literal in an operation named exact search.
    escaped = value.replace("!", "!!").replace("%", "!%").replace("_", "!_")
    return f"%{escaped}%"


def exact_search(path: Path, project_id: str, branch_key: str, query: str, limit: int) -> list[dict[str, Any]]:
    init_db(path)
    pattern = _literal_like_pattern(query)
    with closing(_connect(path)) as conn:
        rows = conn.execute(
            """
            SELECT c.*, f.project_id, f.repo_id, f.source_id, f.source_type, f.revision_key, f.revision_label, f.content_identity, f.branch_key, f.branch_name,
                   f.commit_sha, f.dirty, f.path, f.language, f.parser_id,
                   f.parse_mode, f.parse_status, f.diagnostics_json, s.signature
            FROM code_chunks c JOIN code_files f ON f.file_id=c.file_id
            LEFT JOIN code_symbols s ON s.symbol_id=c.symbol_id
            WHERE f.project_id=? AND f.branch_key=? AND (
                c.symbol_name=? OR c.qualified_name=? OR c.text LIKE ? ESCAPE '!' OR f.path LIKE ? ESCAPE '!'
            )
            ORDER BY
                (c.qualified_name=?) DESC,
                (c.symbol_name=?) DESC,
                (f.path LIKE ? ESCAPE '!') DESC,
                f.path, c.start_line
            LIMIT ?
            """,
            (
                project_id, branch_key, query, query, pattern, pattern,
                query, query, pattern, max(1, min(limit, 200)),
            ),
        ).fetchall()
        out = []
        for index, row in enumerate(rows):
            item = dict(row)
            item["score"] = 4.0 if item["qualified_name"] == query else 3.0 if item["symbol_name"] == query else 1.0 / (index + 1)
            item["retrieval_backend"] = "exact_structural"
            out.append(item)
        return out


def definitions(path: Path, project_id: str, branch_key: str, symbol: str, limit: int = 20) -> list[dict[str, Any]]:
    init_db(path)
    normalized = symbol.strip().strip(".")
    if not normalized:
        return []
    with closing(_connect(path)) as conn:
        rows = conn.execute(
            """
            SELECT s.*, f.project_id, f.repo_id, f.source_id, f.source_type, f.revision_key, f.revision_label, f.content_identity, f.branch_key, f.branch_name,
                   f.commit_sha, f.dirty, f.path, f.language, f.parser_id,
                   f.parse_mode, f.parse_status, f.diagnostics_json,
                   f.content_hash AS file_content_hash,
                   c.chunk_id, c.text, c.embedding_key, c.chunk_part, c.chunk_total,
                   CASE
                     WHEN s.qualified_name = ? COLLATE BINARY THEN 0
                     WHEN s.name = ? COLLATE BINARY THEN 1
                     WHEN lower(s.name) = lower(?) THEN 2
                     WHEN substr(s.qualified_name, -(length(?) + 1)) = ('.' || ?) COLLATE BINARY THEN 3
                     ELSE 9
                   END AS match_tier
            FROM code_symbols s JOIN code_files f ON f.file_id=s.file_id
            LEFT JOIN code_chunks c ON c.symbol_id=s.symbol_id AND c.chunk_part=1
            WHERE f.project_id=? AND f.branch_key=? AND (
                s.qualified_name = ? COLLATE BINARY OR
                s.name = ? COLLATE BINARY OR
                lower(s.name) = lower(?) OR
                substr(s.qualified_name, -(length(?) + 1)) = ('.' || ?) COLLATE BINARY
            )
            ORDER BY match_tier, f.path, s.start_line
            LIMIT ?
            """,
            (
                normalized, normalized, normalized, normalized, normalized,
                project_id, branch_key,
                normalized, normalized, normalized, normalized, normalized,
                max(1, min(max(limit, 20), 200)),
            ),
        ).fetchall()
        if rows:
            best_tier = int(rows[0]["match_tier"])
            rows = [row for row in rows if int(row["match_tier"]) == best_tier][: max(1, min(limit, 100))]
        out = []
        for index, row in enumerate(rows):
            item = dict(row)
            item["symbol_name"] = item["name"]
            item["symbol_kind"] = item["kind"]
            item["score"] = 5.0 - min(index, 4) * 0.25
            item["retrieval_backend"] = "definition_index"
            out.append(item)
        return out


