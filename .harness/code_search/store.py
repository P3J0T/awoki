def _revision_fields(branch: BranchIdentity | SourceRevision) -> dict[str, Any]:
    if isinstance(branch, SourceRevision):
        return {
            "repo_id": branch.repo_id,
            "source_id": branch.source_id,
            "source_type": branch.source_type,
            "revision_key": branch.revision_key,
            "revision_label": branch.revision_label,
            "content_identity": branch.content_identity,
            "branch_key": branch.branch_key or branch.revision_key,
            "branch_name": branch.branch_name or branch.revision_label,
            "commit_sha": branch.commit_sha,
            "dirty": int(branch.dirty),
        }
    return {
        "repo_id": branch.repo_id,
        "source_id": branch.repo_id,
        "source_type": "git",
        "revision_key": branch.branch_key,
        "revision_label": branch.branch_name,
        "content_identity": branch.commit_sha or branch.branch_key,
        "branch_key": branch.branch_key,
        "branch_name": branch.branch_name,
        "commit_sha": branch.commit_sha,
        "dirty": int(branch.dirty),
    }


def file_record(path: Path, project_id: str, branch_key: str, rel_path: str) -> dict[str, Any] | None:
    init_db(path)
    with closing(_connect(path)) as conn:
        row = conn.execute(
            "SELECT * FROM code_files WHERE project_id=? AND branch_key=? AND path=?",
            (project_id, branch_key, rel_path),
        ).fetchone()
        return dict(row) if row else None


def replace_file(
    path: Path,
    *,
    file_id: str,
    project_id: str,
    branch: BranchIdentity | SourceRevision,
    rel_path: str,
    content_hash: str,
    size_bytes: int,
    parsed: ParsedFile,
    indexed_at: str,
) -> dict[str, int]:
    # Parser identifiers describe local syntax occurrences. Re-key them with
    # the branch-specific file occurrence before persistence. Without this,
    # identical code on two branches would collide on the SQLite primary keys
    # even though the content-addressed embedding itself is intentionally
    # reusable across those branches.
    symbol_ids = {
        symbol.symbol_id: hashlib.sha256(
            f"{file_id}|symbol|{symbol.symbol_id}".encode("utf-8")
        ).hexdigest()
        for symbol in parsed.symbols
    }
    references, duplicate_reference_count = _deduplicate_references(parsed.references)
    diagnostics = list(parsed.diagnostics)
    if duplicate_reference_count:
        diagnostics.append(
            f"storage: deduplicated {duplicate_reference_count} identical parser reference emission(s)"
        )

    rev = _revision_fields(branch)
    init_db(path)
    with closing(_connect(path)) as conn:
        with conn:
            old = conn.execute(
                "SELECT file_id FROM code_files WHERE project_id=? AND source_id=? AND revision_key=? AND path=?",
                (project_id, rev["source_id"], rev["revision_key"], rel_path),
            ).fetchone()
            if old:
                old_id = str(old["file_id"])
                conn.execute("DELETE FROM code_chunks_fts WHERE chunk_id IN (SELECT chunk_id FROM code_chunks WHERE file_id=?)", (old_id,))
                conn.execute("DELETE FROM code_files WHERE file_id=?", (old_id,))
            conn.execute(
                """
                INSERT INTO code_files(
                    file_id, project_id, repo_id, source_id, source_type, revision_key,
                    revision_label, content_identity, branch_key, branch_name, commit_sha, dirty,
                    path, language, content_hash, size_bytes, parser_id, parse_mode,
                    parse_status, diagnostics_json, indexed_at
                ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                """,
                (
                    file_id, project_id, rev["repo_id"], rev["source_id"], rev["source_type"],
                    rev["revision_key"], rev["revision_label"], rev["content_identity"],
                    rev["branch_key"], rev["branch_name"], rev["commit_sha"], rev["dirty"],
                    rel_path, parsed.language, content_hash, size_bytes, parsed.parser_id,
                    parsed.parse_mode, parsed.parse_status, json.dumps(diagnostics, ensure_ascii=False), indexed_at,
                ),
            )
            for symbol in parsed.symbols:
                occurrence_symbol_id = symbol_ids[symbol.symbol_id]
                conn.execute(
                    """
                    INSERT INTO code_symbols(
                        symbol_id, file_id, name, qualified_name, kind, parent_symbol_id,
                        start_byte, end_byte, start_line, end_line, signature, content_hash
                    ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)
                    """,
                    (
                        occurrence_symbol_id, file_id, symbol.name, symbol.qualified_name, symbol.kind,
                        symbol_ids.get(symbol.parent_symbol_id or ""), symbol.start_byte, symbol.end_byte,
                        symbol.start_line, symbol.end_line, symbol.signature, symbol.content_hash,
                    ),
                )
            signatures = {symbol_ids[symbol.symbol_id]: symbol.signature for symbol in parsed.symbols}
            for chunk in parsed.chunks:
                occurrence_symbol_id = symbol_ids.get(chunk.symbol_id or "")
                occurrence_chunk_id = hashlib.sha256(
                    f"{file_id}|chunk|{chunk.chunk_id}".encode("utf-8")
                ).hexdigest()
                conn.execute(
                    """
                    INSERT INTO code_chunks(
                        chunk_id, file_id, symbol_id, symbol_name, qualified_name, symbol_kind,
                        chunk_part, chunk_total, start_line, end_line, title, text,
                        content_hash, embedding_key
                    ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                    """,
                    (
                        occurrence_chunk_id, file_id, occurrence_symbol_id, chunk.symbol_name,
                        chunk.qualified_name, chunk.symbol_kind, chunk.chunk_part,
                        chunk.chunk_total, chunk.start_line, chunk.end_line, chunk.title,
                        chunk.text, chunk.content_hash, chunk.embedding_key,
                    ),
                )
                conn.execute(
                    """
                    INSERT INTO code_chunks_fts(
                        chunk_id, project_id, repo_id, source_id, source_type, revision_key, branch_key, path, language,
                        symbol_name, qualified_name, signature, text
                    ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)
                    """,
                    (
                        occurrence_chunk_id, project_id, rev["repo_id"], rev["source_id"], rev["source_type"],
                        rev["revision_key"], rev["branch_key"], rel_path, parsed.language,
                        chunk.symbol_name, chunk.qualified_name, signatures.get(occurrence_symbol_id or "", ""), chunk.text,
                    ),
                )
            for reference in references:
                occurrence_reference_id = hashlib.sha256(
                    f"{file_id}|reference|{reference.reference_id}".encode("utf-8")
                ).hexdigest()
                conn.execute(
                    """
                    INSERT INTO code_references(
                        reference_id, file_id, source_symbol_id, reference_kind, target_name,
                        target_qualified_hint, line, column_no, source_text, control_context_json
                    ) VALUES(?,?,?,?,?,?,?,?,?,?)
                    """,
                    (
                        occurrence_reference_id, file_id,
                        symbol_ids.get(reference.source_symbol_id or ""),
                        reference.reference_kind, reference.target_name,
                        reference.target_qualified_hint, reference.line, reference.column,
                        reference.source_text,
                        json.dumps(list(reference.control_context), ensure_ascii=False),
                    ),
                )
    return {
        "references_input": len(parsed.references),
        "references_stored": len(references),
        "duplicate_references_deduplicated": duplicate_reference_count,
    }


def update_branch_metadata(path: Path, project_id: str, branch: BranchIdentity | SourceRevision, indexed_at: str) -> int:
    """Refresh occurrence metadata without reparsing unchanged source.

    A commit can advance while a file's bytes remain unchanged. The structural
    content and vector are reusable, but every returned hit and Qdrant
    membership must still identify the currently inspected commit/worktree.
    """
    rev = _revision_fields(branch)
    init_db(path)
    with closing(_connect(path)) as conn, conn:
        cursor = conn.execute(
            """
            UPDATE code_files
            SET source_type=?, revision_label=?, content_identity=?, branch_name=?, commit_sha=?, dirty=?, indexed_at=?
            WHERE project_id=? AND source_id=? AND revision_key=? AND (
                source_type<>? OR revision_label<>? OR content_identity<>? OR branch_name<>? OR commit_sha<>? OR dirty<>?
            )
            """,
            (
                rev["source_type"], rev["revision_label"], rev["content_identity"], rev["branch_name"], rev["commit_sha"], rev["dirty"], indexed_at,
                project_id, rev["source_id"], rev["revision_key"],
                rev["source_type"], rev["revision_label"], rev["content_identity"], rev["branch_name"], rev["commit_sha"], rev["dirty"],
            ),
        )
        return int(cursor.rowcount or 0)


def delete_stale_files(path: Path, project_id: str, branch_key: str, current_paths: set[str]) -> list[str]:
    init_db(path)
    removed: list[str] = []
    with closing(_connect(path)) as conn:
        rows = conn.execute(
            "SELECT file_id, path FROM code_files WHERE project_id=? AND branch_key=?",
            (project_id, branch_key),
        ).fetchall()
        with conn:
            for row in rows:
                rel = str(row["path"])
                if rel in current_paths:
                    continue
                file_id = str(row["file_id"])
                conn.execute("DELETE FROM code_chunks_fts WHERE chunk_id IN (SELECT chunk_id FROM code_chunks WHERE file_id=?)", (file_id,))
                conn.execute("DELETE FROM code_files WHERE file_id=?", (file_id,))
                removed.append(rel)
    return removed


def branch_embedding_memberships(path: Path, project_id: str, branch_key: str) -> list[dict[str, Any]]:
    init_db(path)
    with closing(_connect(path)) as conn:
        rows = conn.execute(
            """
            SELECT c.embedding_key, c.chunk_id, c.content_hash, c.text, c.start_line, c.end_line,
                   c.symbol_id, c.symbol_name, c.qualified_name, c.symbol_kind,
                   f.repo_id, f.source_id, f.source_type, f.revision_key, f.content_identity,
                   f.path, f.language, f.commit_sha, f.dirty
            FROM code_chunks c JOIN code_files f ON f.file_id=c.file_id
            WHERE f.project_id=? AND f.branch_key=?
            ORDER BY c.embedding_key, f.path, c.start_line, c.chunk_id
            """,
            (project_id, branch_key),
        ).fetchall()
        return [dict(row) for row in rows]


def synced_vector_memberships(path: Path, project_id: str, branch_key: str) -> list[dict[str, Any]]:
    """Return the last branch membership set confirmed written to Qdrant.

    This is deliberately separate from the current SQLite code index. If a
    source update succeeds locally but the remote vector update fails, the
    previous snapshot is retained so the next retry can still remove stale
    remote memberships rather than forgetting what Qdrant may contain.
    """
    init_db(path)
    with closing(_connect(path)) as conn:
        rows = conn.execute(
            """
            SELECT embedding_key, chunk_id, content_hash, text, repo_id, source_id, source_type,
                   revision_key, content_identity, path, symbol_id, symbol_name, qualified_name, symbol_kind, language,
                   start_line, end_line, commit_sha, dirty
            FROM code_vector_memberships
            WHERE project_id=? AND branch_key=?
            ORDER BY embedding_key, path, start_line, chunk_id
            """,
            (project_id, branch_key),
        ).fetchall()
        return [dict(row) for row in rows]


