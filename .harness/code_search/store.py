SCHEMA_VERSION = 4


class ReferenceIdentityConflict(ValueError):
    """Raised when one parser reference id describes conflicting occurrences."""


def _reference_payload(reference: CodeReference) -> tuple[Any, ...]:
    """Return every persisted field that a parser reference id is expected to identify.

    ``reference_id`` is generated by parsers from the source occurrence identity.
    Duplicate emissions of the same occurrence are harmless and are collapsed at
    the storage boundary. Reusing an id for different persisted content is not
    harmless: choosing one row would silently corrupt graph/control-flow evidence,
    so that case is rejected before the existing file occurrence is touched.
    """
    return (
        reference.source_symbol_id or "",
        reference.reference_kind,
        reference.target_name,
        reference.target_qualified_hint,
        int(reference.line),
        int(reference.column),
        reference.source_text,
        tuple(reference.control_context),
    )


def _deduplicate_references(references: Iterable[CodeReference]) -> tuple[list[CodeReference], int]:
    unique: list[CodeReference] = []
    by_id: dict[str, CodeReference] = {}
    duplicate_count = 0
    for reference in references:
        prior = by_id.get(reference.reference_id)
        if prior is None:
            by_id[reference.reference_id] = reference
            unique.append(reference)
            continue
        if _reference_payload(prior) == _reference_payload(reference):
            duplicate_count += 1
            continue
        raise ReferenceIdentityConflict(
            "parser emitted conflicting code references with the same reference_id "
            f"{reference.reference_id}; refusing to choose one occurrence"
        )
    return unique, duplicate_count


