def _edge_id(reference_id: str, target: str) -> str:
    import hashlib
    return hashlib.sha256(f"{reference_id}|{target}".encode()).hexdigest()


def _decode_context(value: Any) -> list[str]:
    try:
        parsed = json.loads(str(value or "[]"))
    except json.JSONDecodeError:
        return []
    return [str(item) for item in parsed] if isinstance(parsed, list) else []


def _qualified_candidates(
    conn: sqlite3.Connection,
    *,
    branch_key: str,
    suffix: str,
) -> list[sqlite3.Row]:
    normalized = suffix.strip(".")
    if not normalized:
        return []
    if "->" in normalized:
        return conn.execute(
            """
            SELECT s.symbol_id FROM code_symbols s JOIN code_files f ON f.file_id=s.file_id
            WHERE f.branch_key=? AND s.qualified_name=? COLLATE BINARY
            ORDER BY f.path, s.start_line
            """,
            (branch_key, normalized),
        ).fetchall()
    return conn.execute(
        """
        SELECT s.symbol_id FROM code_symbols s JOIN code_files f ON f.file_id=s.file_id
        WHERE f.branch_key=? AND (
            s.qualified_name = ? COLLATE BINARY OR
            substr(s.qualified_name, -(length(?) + 1)) = ('.' || ?) COLLATE BINARY
        )
        ORDER BY f.path, s.start_line
        """,
        (branch_key, normalized, normalized, normalized),
    ).fetchall()


def _merge_import_qualification(imported_hint: str, tail: str) -> str:
    """Join an imported module/symbol with a qualified call without duplication."""
    base = [part for part in imported_hint.strip(".").split(".") if part]
    suffix = [part for part in tail.strip(".").split(".") if part]
    overlap = 0
    for size in range(min(len(base), len(suffix)), 0, -1):
        if base[-size:] == suffix[:size]:
            overlap = size
            break
    return ".".join(base + suffix[overlap:])


def resolve_call_graph(path: Path, branch_key: str) -> dict[str, int]:
    """Resolve only static call edges whose target can be selected uniquely."""
    init_db(path)
    resolved = ambiguous = unresolved = 0
    with closing(_connect(path)) as conn:
        refs = conn.execute(
            """
            SELECT r.*, f.path AS source_path, s.parent_symbol_id AS source_parent_symbol_id
            FROM code_references r
            JOIN code_files f ON f.file_id=r.file_id
            JOIN code_symbols s ON s.symbol_id=r.source_symbol_id
            WHERE f.branch_key=? AND r.reference_kind='call' AND r.source_symbol_id IS NOT NULL
            """,
            (branch_key,),
        ).fetchall()
        with conn:
            conn.execute("DELETE FROM code_edges WHERE branch_key=?", (branch_key,))
            for ref in refs:
                target_name = str(ref["target_name"])
                qualified_hint = str(ref["target_qualified_hint"] or "").strip()
                candidates: list[sqlite3.Row] = []
                method = "unresolved"
                confidence = "low"

                # Smali and other deterministic textual IRs can encode an exact
                # declaring type + method descriptor in the call itself. Resolve
                # that identity directly rather than degrading it to a name-only
                # guess.
                if qualified_hint and "->" in qualified_hint:
                    candidates = _qualified_candidates(conn, branch_key=branch_key, suffix=qualified_hint)
                    method = "qualified_exact"
                    confidence = "high" if len(candidates) == 1 else "low"

                # self.foo()/this.foo() resolves first within the containing class.
                if ref["source_parent_symbol_id"] and qualified_hint.startswith(("self.", "this.")):
                    candidates = conn.execute(
                        """
                        SELECT s.symbol_id FROM code_symbols s JOIN code_files f ON f.file_id=s.file_id
                        WHERE f.branch_key=? AND f.path=? AND s.parent_symbol_id=? AND s.name=?
                        ORDER BY s.start_line
                        """,
                        (branch_key, ref["source_path"], ref["source_parent_symbol_id"], target_name),
                    ).fetchall()
                    method = "same_type_member"
                    confidence = "medium"

                # A unique same-file definition is deterministic only for an
                # unqualified call. Resolving obj.foo() merely because foo is
                # unique would be unsound without receiver type information.
                if not candidates and (not qualified_hint or "." not in qualified_hint):
                    candidates = conn.execute(
                        """
                        SELECT s.symbol_id FROM code_symbols s JOIN code_files f ON f.file_id=s.file_id
                        WHERE f.branch_key=? AND f.path=? AND s.name=?
                        ORDER BY (s.parent_symbol_id IS NULL) DESC, s.start_line
                        """,
                        (branch_key, ref["source_path"], target_name),
                    ).fetchall()
                    method = "same_file_exact"
                    confidence = "medium"

                # Qualified receiver calls are resolved only through an explicit
                # import binding. A textual receiver such as service.run() may
                # be a local variable, dynamically injected object, or class; a
                # matching qualified symbol name alone is not enough evidence.
                if len(candidates) != 1:
                    root_name = qualified_hint.split(".", 1)[0] if qualified_hint else target_name
                    imports = conn.execute(
                        """
                        SELECT target_name, target_qualified_hint
                        FROM code_references
                        WHERE file_id=? AND reference_kind='import' AND target_name=?
                        """,
                        (ref["file_id"], root_name),
                    ).fetchall()
                    imported_candidates: dict[str, sqlite3.Row] = {}
                    for imported in imports:
                        imported_hint = str(imported["target_qualified_hint"] or "")
                        if qualified_hint and "." in qualified_hint:
                            tail = qualified_hint.split(".", 1)[1]
                            imported_hint = _merge_import_qualification(imported_hint, tail)
                        for candidate in _qualified_candidates(conn, branch_key=branch_key, suffix=imported_hint):
                            imported_candidates[str(candidate["symbol_id"])] = candidate
                    if imported_candidates:
                        candidates = list(imported_candidates.values())
                        method = "import_qualified"
                        confidence = "medium" if len(candidates) == 1 else "low"

                if len(candidates) != 1 and (not qualified_hint or "." not in qualified_hint):
                    candidates = conn.execute(
                        """
                        SELECT s.symbol_id FROM code_symbols s JOIN code_files f ON f.file_id=s.file_id
                        WHERE f.branch_key=? AND s.name=?
                        ORDER BY f.path, s.start_line
                        """,
                        (branch_key, target_name),
                    ).fetchall()
                    method = "unique_branch_name"
                    confidence = "low"

                count = len(candidates)
                if count == 1:
                    target_id = str(candidates[0]["symbol_id"])
                    status = "resolved"
                    resolved += 1
                elif count > 1:
                    target_id = None
                    status = "ambiguous"
                    ambiguous += 1
                else:
                    target_id = None
                    status = "unresolved"
                    unresolved += 1
                conn.execute(
                    """
                    INSERT INTO code_edges(
                        edge_id, branch_key, source_symbol_id, target_symbol_id, target_name,
                        edge_kind, line, confidence, resolution_status, resolution_method,
                        candidate_count, source_text, control_context_json
                    ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)
                    """,
                    (
                        _edge_id(str(ref["reference_id"]), target_id or target_name),
                        branch_key, ref["source_symbol_id"], target_id, target_name, "call",
                        ref["line"], confidence, status, method, count,
                        str(ref["source_text"] or ""), str(ref["control_context_json"] or "[]"),
                    ),
                )
    return {"resolved": resolved, "ambiguous": ambiguous, "unresolved": unresolved}


